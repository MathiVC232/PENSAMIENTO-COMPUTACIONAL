# Lista de ejemplo
mi_lista = [10, 20, 30, 40, 50]

# Acceso por índice
print(mi_lista[2])  # 30

# Slice (sub-secuencia)
print(mi_lista[1:4])  # [20, 30, 40]

# Tupla de ejemplo
mi_tupla = (1, 2, 3, 4, 5)

# Acceso por índice
print(mi_tupla[3])  # 4

# Slice
print(mi_tupla[0:3])  # (1, 2, 3)

# Crear un rango
mi_rango = range(1, 6)  # Números del 1 al 5

# Convertir a lista para verlos
print(list(mi_rango))  # [1, 2, 3, 4, 5]